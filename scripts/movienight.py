"""Movie Night (CeeJay.dk, MIT) on the topt blur: fx/MovieNight.fx.

Fills the black bars of letterboxed / pillarboxed video with a blurred continuation of the picture
(each bar pixel shows the picture point CeeJay's original maps it to). The blur is TOPT_Blur's (the
same size classes and per-GPU tables, make_effect.BODY), but its passes draw only the strips of the
picture the bars show, plus the blur's reach, and the first downsample reads the screen clamped to the
picture, so the black bars do not darken the glow. Written by scripts.make_effect (same tables).
"""
from __future__ import annotations

from scripts.make_effect import BODY

HEAD = r"""/*------------------.
| :: Description :: |
'-------------------/

	Movie Night (name not final)

	Author: CeeJay.dk
	License: MIT

	About:
	Fills the black bars of letterboxed (or pillarboxed) video with a soft,
	blurred continuation of the picture.

	The blur is the topt blur (TOPT_Blur.fx, generated by the topt texture-sample
	optimizer): a wide downsample, a Gaussian at low resolution and a smooth
	upsample. Its passes only draw the strips of the picture next to the bars
	(plus the reach of the blur), and the downsample reads the screen clamped to
	the picture, so the black bars do not darken the glow.

	History:
	(*) Feature (+) Improvement	(x) Bugfix (-) Information (!) Compatibility

	Version 0.4 WIP
	* Real blur (topt) instead of the noise-scattered read; left / right bars
	  map the picture the same way as top / bottom.
*/

#ifndef MOVIENIGHT_BLUR_SIZE
	#define MOVIENIGHT_BLUR_SIZE 32 // blur sigma in pixels at 1080p (2..200); scales with resolution
#endif
#define TOPT_BLUR_SIZE MOVIENIGHT_BLUR_SIZE

uniform float Top <
	ui_type = "drag"; ui_min = 0.0; ui_max = 1000.0; ui_step = 1.0;
	ui_label = "Top bar (px)";
> = 278.0;

uniform float Bottom <
	ui_type = "drag"; ui_min = 0.0; ui_max = 1000.0; ui_step = 1.0;
	ui_label = "Bottom bar (px)";
> = 278.0;

uniform float Left <
	ui_type = "drag"; ui_min = 0.0; ui_max = 1000.0; ui_step = 1.0;
	ui_label = "Left bar (px)";
> = 0.0;

uniform float Right <
	ui_type = "drag"; ui_min = 0.0; ui_max = 1000.0; ui_step = 1.0;
	ui_label = "Right bar (px)";
> = 0.0;

uniform float Opacity <
	ui_type = "drag"; ui_min = 0.0; ui_max = 1.0; ui_step = 0.01;
	ui_label = "Opacity";
> = 0.5;

uniform float Zoom <
	ui_type = "drag"; ui_min = 1.0; ui_max = 10.0; ui_step = 0.1;
	ui_label = "Zoom (bar geometry, for testing)";
> = 1.0;

static const float2 MN_PX = float2(BUFFER_RCP_WIDTH, BUFFER_RCP_HEIGHT);

// The picture rectangle (uv), between the bars.
float2 MN_PicMin() { return float2(Left, Top) * MN_PX; }
float2 MN_PicMax() { return 1.0 - float2(Right, Bottom) * MN_PX; }

// The blur reads the screen only inside the picture (half a pixel in), so the bars do not darken it.
#define TOPT_SRC_UV(uv) clamp(uv, MN_PicMin() + 0.5 * MN_PX, MN_PicMax() - 0.5 * MN_PX)

"""

TAIL = r"""
#if TOPT_SMALL
	#error "Movie Night needs MOVIENIGHT_BLUR_SIZE >= 2"
#endif

// The picture point a bar pixel shows (CeeJay's mapping): pulled towards the centre by the bars'
// share of the screen, so a bar shows the picture strip next to it, mirrored.
float2 MN_Map(float2 uv)
{
	const float2 d = float2(Left + Right, Top + Bottom) * MN_PX;
	return uv + (0.5 - uv) * d;
}

/*
	The strips the blur passes draw: for each bar, the picture strip it shows
	(MN_Map of the bar), widened by the blur's reach (3 sigma plus the
	downsample footprint), as two triangles. A side without a bar gets an
	empty strip.
*/
void MN_StripVS(in uint id : SV_VertexID, out float4 position : SV_Position, out float2 texcoord : TEXCOORD)
{
	const float sigma = TOPT_BLUR_SIZE * TOPT_SizeTune * BUFFER_HEIGHT / 1080.0;
	const float2 m = (3.0 * sigma + 2.0 * TOPT_DIVL) * MN_PX; // reach, uv
	const float2 lo = MN_PicMin(), hi = MN_PicMax();
	const float2 d = float2(Left + Right, Top + Bottom) * MN_PX;
	const uint side = id / 6; // 0 top, 1 bottom, 2 left, 3 right
	float2 a = 0.0, b = 0.0; // strip corners
	if (side == 0 && Top > 0.0)
	{
		a = float2(0.0, min(0.5 * d.y, lo.y) - m.y);
		b = float2(1.0, lo.y + (0.5 - lo.y) * d.y + m.y);
	}
	else if (side == 1 && Bottom > 0.0)
	{
		a = float2(0.0, hi.y + (0.5 - hi.y) * d.y - m.y);
		b = float2(1.0, max(1.0 - 0.5 * d.y, hi.y) + m.y);
	}
	else if (side == 2 && Left > 0.0)
	{
		a = float2(min(0.5 * d.x, lo.x) - m.x, 0.0);
		b = float2(lo.x + (0.5 - lo.x) * d.x + m.x, 1.0);
	}
	else if (side == 3 && Right > 0.0)
	{
		a = float2(hi.x + (0.5 - hi.x) * d.x - m.x, 0.0);
		b = float2(max(1.0 - 0.5 * d.x, hi.x) + m.x, 1.0);
	}
	a = saturate(a);
	b = saturate(b);
	const uint k = id % 6; // two triangles: a, (b.x a.y), (a.x b.y) and (b.x a.y), b, (a.x b.y)
	texcoord = float2(k == 1 || k == 3 || k == 4 ? b.x : a.x, k == 2 || k == 4 || k == 5 ? b.y : a.y);
	position = float4(texcoord * float2(2.0, -2.0) + float2(-1.0, 1.0), 0.0, 1.0);
}

/*
	The bars: four large triangles, one per bar (CeeJay's layout).
		1
	( 0, 2)
	[-1, 3]   [ 3, 3]
		.
		|`.
		|  `.
		|    `.
		'------`
		0         2
	( 0, 0)   ( 2, 0)
	[-1,-1]   [ 3,-1]
*/
void MN_BarsVS(in uint id : SV_VertexID, out float4 position : SV_Position, out float2 texcoord : TEXCOORD)
{
	const float ID0 = Top * MN_PX.y;
	const float ID3 = 1.0 - Bottom * MN_PX.y;
	const float ID6 = Left * MN_PX.x;
	const float ID9 = 1.0 - Right * MN_PX.x;

	[call] switch (id)
	{
		default: texcoord = float2(ID6, ID0);  break; // top
		case 1:  texcoord = float2(ID6, -1.0); break;
		case 2:  texcoord = float2(2.0, ID0);  break;
		case 3:  texcoord = float2(ID9, ID3);  break; // bottom
		case 4:  texcoord = float2(ID9, 2.0);  break;
		case 5:  texcoord = float2(-1.0, ID3); break;
		case 6:  texcoord = float2(ID6, ID3);  break; // left
		case 7:  texcoord = float2(-1.0, ID3); break;
		case 8:  texcoord = float2(ID6, -1.0); break;
		case 9:  texcoord = float2(ID9, ID0);  break; // right
		case 10: texcoord = float2(2.0, ID0);  break;
		case 11: texcoord = float2(ID9, 2.0);  break;
	}
	position = float4(texcoord * float2(2.0, -2.0) + float2(-1.0, 1.0), 1.0, Zoom);
}

float3 MN_BarsPS(float4 vpos : SV_Position, float2 texcoord : TEXCOORD) : SV_Target
{
	float3 color = tex2D(ReShade::BackBuffer, texcoord).rgb;
	if (all(color <= 2.0 / 255.0)) // only the black of the bars (subtitles stay)
		color = TOPT_BlurResolve(MN_Map(texcoord)) * Opacity;
	return saturate(color);
}

technique MovieNight
{
	pass Down1 { PrimitiveTopology = TRIANGLELIST; VertexCount = 24; VertexShader = MN_StripVS; PixelShader = TOPT_Down1PS; RenderTarget = TOPT_tDown1; }
#if TOPT_STEPS > 1
	pass Down2 { PrimitiveTopology = TRIANGLELIST; VertexCount = 24; VertexShader = MN_StripVS; PixelShader = TOPT_Down2PS; RenderTarget = TOPT_tDown2; }
#endif
#if TOPT_SEP
	pass BlurH { PrimitiveTopology = TRIANGLELIST; VertexCount = 24; VertexShader = MN_StripVS; PixelShader = TOPT_BlurHPS; RenderTarget = TOPT_tBlurH; }
	pass BlurV { PrimitiveTopology = TRIANGLELIST; VertexCount = 24; VertexShader = MN_StripVS; PixelShader = TOPT_BlurVPS; RenderTarget = TOPT_tBlur; }
#else
	pass Blur { PrimitiveTopology = TRIANGLELIST; VertexCount = 24; VertexShader = MN_StripVS; PixelShader = TOPT_BlurPS; RenderTarget = TOPT_tBlur; }
#endif
#if TOPT_UPSTEPS > 1
	pass Up { PrimitiveTopology = TRIANGLELIST; VertexCount = 24; VertexShader = MN_StripVS; PixelShader = TOPT_UpPS; RenderTarget = TOPT_tUp; }
#endif
	pass Bars { PrimitiveTopology = TRIANGLELIST; VertexCount = 12; VertexShader = MN_BarsVS; PixelShader = MN_BarsPS; }
}
"""

TEMPLATE = HEAD + BODY + TAIL
