"""SweetClarity (working name; local contrast, "clarity") on the topt blur: fx/SweetClarity.fx.

Boosts the brightness detail around a smooth base layer, the guided filter of the picture with itself
(scripts/sweetclarity_sim.py: unsharp masking's halos at strong edges go from about 31 to 1-3 levels at the same
texture boost). The blur is TOPT_Blur's (make_effect.BODY: the same size classes and per-GPU tables) on two
channels, the brightness and its square (their local mean and spread); the final pass works out the base
per pixel. Brightness only: the colour is kept. Written by scripts.make_effect (same tables).
"""
from __future__ import annotations

from scripts.make_effect import BODY

HEAD = r"""/*
  SweetClarity (working name)

  Makes the picture look crisper and more detailed: brings out texture and fine shading (fabric, skin,
  stone, clouds) without the bright and dark outlines around strong edges that plain sharpening leaves.
  Only the brightness is changed, the colours stay as they are.

  How: each pixel is compared with a smooth version of its surroundings (the base layer) and the
  difference is boosted. The base follows strong edges instead of blurring across them (a guided filter
  of the picture with itself), so they get no halos. The blur is the topt blur (TOPT_Blur.fx: the size
  classes and per-GPU tables of TOPT_BlurTables.fxh) on two channels, the brightness and its square.

  Video and games: SDR and HDR10 (PQ) / HLG work on the stored values; scRGB (linear HDR) works on the
  brightness encoded as PQ, so the effect is the same in bright and dark parts.
  Generated by scripts/make_effect.py (scripts/sweetclarity.py).
*/

#ifndef SWEETCLARITY_SIZE
	#define SWEETCLARITY_SIZE 24 // size of the surroundings each pixel is compared with: sigma in pixels at 1080p (2..200); scales with resolution
#endif
#ifndef SWEETCLARITY_FORMAT
	#define SWEETCLARITY_FORMAT RG16F // blur buffers (mean and square of the brightness): RG16F, or RG32F for the most precision
#endif
#undef BLUR_SIZE
#define BLUR_SIZE SWEETCLARITY_SIZE

uniform float SC_Strength <
	ui_type = "slider"; ui_min = 0.0; ui_max = 2.0; ui_step = 0.01;
	ui_label = "Strength";
	ui_tooltip = "How much the detail is brought out (0.5: fine detail about 1.5 x as strong).";
> = 0.6;

uniform float SC_Edge <
	ui_type = "slider"; ui_min = 1.0; ui_max = 64.0; ui_step = 1.0;
	ui_label = "Edge threshold (8-bit levels)";
	ui_tooltip = "Brightness differences well below this are brought out; strong edges well above it are\n"
	             "left alone, so they get no bright or dark outlines. Higher: more is brought out, with more\n"
	             "outline at strong edges.";
> = 12.0;

uniform float SC_Protect <
	ui_type = "slider"; ui_min = 0.0; ui_max = 1.0; ui_step = 0.01;
	ui_label = "Protect shadows and highlights";
	ui_tooltip = "Less effect in the darkest and brightest parts (0: the same everywhere, 1: none at black\n"
	             "and white).";
> = 0.5;

uniform float SC_Limit <
	ui_type = "slider"; ui_min = 1.0; ui_max = 64.0; ui_step = 1.0;
	ui_label = "Limit (8-bit levels)";
	ui_tooltip = "The most any pixel is changed; the change approaches it softly.";
> = 24.0;

uniform int SC_View <
	ui_type = "combo"; ui_items = "Result\0Base layer (the smooth picture)\0Detail (what is brought out, x4; grey = none)\0";
	ui_label = "View";
> = 0;

// What the blur passes blur: the guide brightness y (minus 0.5, so the square keeps its precision in half
// floats) and its square, i.e. the local mean and spread of y.
#define BLUR_CUSTOM_CHANNELS
#define BLUR_FMT SWEETCLARITY_FORMAT
#define BLUR_T float2
#define BLUR_CH rg
#define BLUR_OUT(c) float4(c, 0.0, 1.0)
#define BLUR_FROM_SRC(rgb) SC_Moments(SC_Guide(rgb))

#if defined(BUFFER_COLOR_SPACE) && BUFFER_COLOR_SPACE == 2
	#define SC_SCRGB 1 // linear HDR: work on the brightness as PQ
#else
	#define SC_SCRGB 0
#endif

float SC_Luma(float3 c) { return dot(c, float3(0.2126, 0.7152, 0.0722)); }

#if SC_SCRGB
// PQ (SMPTE ST 2084) of scRGB brightness (1 = 80 nits), and back.
float SC_ToPQ(float y)
{
	const float p = pow(max(y, 0.0) * (80.0 / 10000.0), 0.1593017578);
	return pow((0.8359375 + 18.8515625 * p) / (1.0 + 18.6875 * p), 78.84375);
}
float SC_FromPQ(float e)
{
	const float p = pow(saturate(e), 1.0 / 78.84375);
	return pow(max(p - 0.8359375, 0.0) / (18.8515625 - 18.6875 * p), 1.0 / 0.1593017578) * (10000.0 / 80.0);
}
float SC_Guide(float3 c) { return SC_ToPQ(SC_Luma(c)); }
#else
float SC_Guide(float3 c) { return SC_Luma(c); }
#endif

float2 SC_Moments(float y)
{
	const float t = y - 0.5;
	return float2(t, t * t);
}

"""

