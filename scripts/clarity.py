"""Clarity (local contrast) on the topt blur: fx/TOPT_Clarity.fx.

Boosts the brightness detail around a smooth base layer, the guided filter of the picture with itself
(scripts/clarity_sim.py: unsharp masking's halos at strong edges go from about 31 to 1-3 levels at the same
texture boost). The blur is TOPT_Blur's (make_effect.BODY: the same size classes and per-GPU tables) on two
channels, the brightness and its square (their local mean and spread); the final pass works out the base
per pixel. Brightness only: the colour is kept. Written by scripts.make_effect (same tables).
"""
from __future__ import annotations

from scripts.make_effect import BODY

HEAD = r"""/*
  TOPT Clarity: local contrast (clarity) on the topt blur.

  Boosts the brightness detail of the picture against a smooth base layer. The base is the guided filter
  of the picture with itself: where the local contrast is far above Edge threshold (a strong edge) the
  base follows the picture, so the edge gets no halo; finer, weaker detail is boosted. Brightness only,
  the colour is kept. The blur is the topt blur (TOPT_Blur.fx: the size classes and per-GPU tables of
  TOPT_BlurTables.fxh) on two channels, the brightness and its square, i.e. their local mean and spread.

  Video and games: SDR and HDR10 (PQ) / HLG work on the stored values; scRGB (linear HDR) works on the
  brightness encoded as PQ, so the effect is the same in bright and dark parts.
  Generated by scripts/make_effect.py (scripts/clarity.py).
*/

#ifndef CLARITY_SIZE
	#define CLARITY_SIZE 24 // sigma of the local area in pixels at 1080p (2..200); scales with resolution
#endif
#ifndef CLARITY_FORMAT
	#define CLARITY_FORMAT RG16F // blur buffers (mean and square of the brightness): RG16F, or RG32F for the most precision
#endif
#undef BLUR_SIZE
#define BLUR_SIZE CLARITY_SIZE

uniform float CL_Strength <
	ui_type = "slider"; ui_min = 0.0; ui_max = 2.0; ui_step = 0.01;
	ui_label = "Strength";
	ui_tooltip = "How much the detail is boosted (0.5: weak detail about 1.5 x).";
> = 0.6;

uniform float CL_Edge <
	ui_type = "slider"; ui_min = 1.0; ui_max = 64.0; ui_step = 1.0;
	ui_label = "Edge threshold (8-bit levels)";
	ui_tooltip = "Local contrast well below this is boosted; well above it (strong edges) is left alone, so\n"
	             "edges get no halos. Higher: more is boosted, with more halo at strong edges.";
> = 12.0;

uniform float CL_Protect <
	ui_type = "slider"; ui_min = 0.0; ui_max = 1.0; ui_step = 0.01;
	ui_label = "Protect shadows and highlights";
	ui_tooltip = "Less boost towards black and white (0: the same everywhere, 1: none at black and white).";
> = 0.5;

uniform float CL_Limit <
	ui_type = "slider"; ui_min = 1.0; ui_max = 64.0; ui_step = 1.0;
	ui_label = "Limit (8-bit levels)";
	ui_tooltip = "The change per pixel approaches this softly and never exceeds it.";
> = 24.0;

uniform int CL_View <
	ui_type = "combo"; ui_items = "Result\0Base layer\0Detail (x4, grey = none)\0";
	ui_label = "View";
> = 0;

// What the blur passes blur: the guide brightness y (minus 0.5, so the square keeps its precision in half
// floats) and its square, i.e. the local mean and spread of y.
#define BLUR_CUSTOM_CHANNELS
#define BLUR_FMT CLARITY_FORMAT
#define BLUR_T float2
#define BLUR_CH rg
#define BLUR_OUT(c) float4(c, 0.0, 1.0)
#define BLUR_FROM_SRC(rgb) CL_Moments(CL_Guide(rgb))

#if defined(BUFFER_COLOR_SPACE) && BUFFER_COLOR_SPACE == 2
	#define CL_SCRGB 1 // linear HDR: work on the brightness as PQ
#else
	#define CL_SCRGB 0
#endif

float CL_Luma(float3 c) { return dot(c, float3(0.2126, 0.7152, 0.0722)); }

#if CL_SCRGB
// PQ (SMPTE ST 2084) of scRGB brightness (1 = 80 nits), and back.
float CL_ToPQ(float y)
{
	const float p = pow(max(y, 0.0) * (80.0 / 10000.0), 0.1593017578);
	return pow((0.8359375 + 18.8515625 * p) / (1.0 + 18.6875 * p), 78.84375);
}
float CL_FromPQ(float e)
{
	const float p = pow(saturate(e), 1.0 / 78.84375);
	return pow(max(p - 0.8359375, 0.0) / (18.8515625 - 18.6875 * p), 1.0 / 0.1593017578) * (10000.0 / 80.0);
}
float CL_Guide(float3 c) { return CL_ToPQ(CL_Luma(c)); }
#else
float CL_Guide(float3 c) { return CL_Luma(c); }
#endif

float2 CL_Moments(float y)
{
	const float t = y - 0.5;
	return float2(t, t * t);
}

"""

