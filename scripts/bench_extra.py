"""Hand-written benchmark effects (written by scripts.make_fx):

TOPT_Bench_Noise.fx   where per-pixel random numbers come from: ALU (IGN, R2,
                      hash), a hard-coded 4 x 4 table indexed by position, or
                      blue-noise textures of 4^2 .. 512^2 texels and several
                      formats (RG8, R8, RGBA8, R8 with two packed 4-bit values).
                      Each source feeds a scatter ("frosted glass") pass:
                      _1 = one lookup, 4 taps (a realistic final pass),
                      _8 = 8 lookups, 8 taps (stress, exposes the lookup cost).
TOPT_Bench_Layout.fx  separable full-res Gaussian blurs: H then V, V then H,
                      H written transposed (so both passes read along the
                      other axis of the warp), and H/V split over two render
                      targets (even / odd columns) per pass.
"""
from __future__ import annotations

import math

HEAD = """// Auto-generated by topt (scripts/make_fx.py) - do not edit by hand.
#include "ReShade.fxh"
"""

BN_SIZES = (4, 8, 16, 32, 64, 128, 256, 512)
TABLE16 = [((i * 0.7548776662 + 0.5) % 1.0, (i * 0.5698402910 + 0.5) % 1.0) for i in range(16)]  # R2 points


def _f(v: float) -> str:
    s = f"{v:.7g}"
    return s if any(c in s for c in ".e") else s + ".0"


def _bn_tex(name: str, file: str, size: int, fmt: str) -> str:
    return (f'texture {name}_t < source = "{file}"; > {{ Width = {size}; Height = {size}; Format = {fmt}; }};\n'
            f'sampler {name}_s {{ Texture = {name}_t; AddressU = WRAP; AddressV = WRAP; '
            f'MagFilter = POINT; MinFilter = POINT; MipFilter = POINT; }};\n')


# Each source: (name, HLSL body of float2 Noise_<name>(float2 p, float i)), extra declarations
def _sources() -> list:
    out = [("Fixed", "return float2(0.375, 0.625);", ""),
           # interleaved gradient noise (Jimenez 2014), two decorrelated copies
           ("IGN", "p += i * float2(5.588238, 5.588238);\n"
                   "\treturn float2(frac(52.9829189 * frac(dot(p, float2(0.06711056, 0.00583715)))),\n"
                   "\t              frac(52.9829189 * frac(dot(p + float2(47.0, 17.0), float2(0.06711056, 0.00583715)))));", ""),
           # R2 low-discrepancy sequence over the pixel grid
           ("R2", "p += i * float2(7.0, 13.0);\n"
                  "\treturn frac(float2(dot(p, float2(0.7548777, 0.5698403)), dot(p, float2(0.5698403, 0.7548777))) + 0.5);", ""),
           # "hash without sine" (Dave Hoskins, MIT)
           ("Hash", "float3 q = frac(float3(p.x, p.y, p.x + i * 17.0) * float3(0.1031, 0.1030, 0.0973));\n"
                    "\tq += dot(q, q.yzx + 33.33);\n\treturn frac((q.xx + q.yz) * q.zy);", ""),
           # hard-coded 16 positions, picked by the pixel position (x & 3) + 4 (y & 3)
           ("Table16", "const float2 t = frac((p + i * float2(1.0, 2.0)) * 0.25);\n"
                       "\treturn TOPT_N_TAB[(int)dot(t, float2(4.0, 16.0))];",
            "static const float2 TOPT_N_TAB[16] = {\n\t" +
            ", ".join(f"float2({_f(x)}, {_f(y)})" for x, y in TABLE16) + "\n};\n")]
    for n in BN_SIZES:
        out.append((f"BN{n}_RG8", f"return tex2Dlod(TOPT_bn{n}rg_s, float4((p + i * float2(17.0, 29.0) + 0.5) / {n}.0, 0.0, 0.0)).rg;",
                    _bn_tex(f"TOPT_bn{n}rg", f"topt_bn{n}_RG8.png", n, "RG8")))
    out.append(("BN64_R8", "const float v = tex2Dlod(TOPT_bn64r_s, float4((p + i * float2(17.0, 29.0) + 0.5) / 64.0, 0.0, 0.0)).r;\n"
                           "\treturn float2(v, frac(v + 0.6180340));",
                _bn_tex("TOPT_bn64r", "topt_bn64_R8.png", 64, "R8")))
    out.append(("BN64_R8P", "const float v = tex2Dlod(TOPT_bn64p_s, float4((p + i * float2(17.0, 29.0) + 0.5) / 64.0, 0.0, 0.0)).r * 15.9375;\n"
                            "\treturn float2(floor(v), frac(v) * 16.0) * 0.0625 + 0.03125; // two 4-bit values in one byte",
                _bn_tex("TOPT_bn64p", "topt_bn64_R8P.png", 64, "R8")))
    out.append(("BN64_RGBA8", "const float4 v = tex2Dlod(TOPT_bn64x_s, float4((p + floor(i * 0.5) * float2(17.0, 29.0) + 0.5) / 64.0, 0.0, 0.0));\n"
                              "\treturn frac(i * 0.5) > 0.25 ? v.ba : v.rg; // two pairs per read",
                _bn_tex("TOPT_bn64x", "topt_bn64_RGBA8.png", 64, "RGBA8")))
    return out


def noise_effect() -> str:
    src = _sources()
    out = [HEAD, "#define TOPT_N_RADIUS 6.0 // scatter radius in pixels\n"]
    for name, body, decl in src:
        out.append(decl)
        out.append(f"float2 TOPT_Noise_{name}(float2 p, float i)\n{{\n\t{body}\n}}\n")
    for name, _, _ in src:
        out.append(f"""float4 TOPT_N_{name}_1PS(float4 pos : SV_Position, float2 uv : TEXCOORD) : SV_Target
{{
	// one lookup: rotate and scale a 4-point disk pattern
	const float2 u = TOPT_Noise_{name}(floor(pos.xy), 0.0);
	float2 cs; sincos(6.2831853 * u.x, cs.y, cs.x);
	cs *= sqrt(u.y) * TOPT_N_RADIUS * BUFFER_PIXEL_SIZE;
	float3 c = tex2Dlod(ReShade::BackBuffer, float4(uv + cs, 0.0, 0.0)).rgb;
	c += tex2Dlod(ReShade::BackBuffer, float4(uv - cs, 0.0, 0.0)).rgb;
	c += tex2Dlod(ReShade::BackBuffer, float4(uv + float2(-cs.y, cs.x), 0.0, 0.0)).rgb;
	c += tex2Dlod(ReShade::BackBuffer, float4(uv + float2(cs.y, -cs.x), 0.0, 0.0)).rgb;
	return float4(c * 0.25, 1.0);
}}
float4 TOPT_N_{name}_8PS(float4 pos : SV_Position, float2 uv : TEXCOORD) : SV_Target
{{
	// stress: 8 lookups, one random disk position each
	float3 c = 0.0;
	[unroll] for (int i = 0; i < 8; i++)
	{{
		const float2 u = TOPT_Noise_{name}(floor(pos.xy), i);
		float2 cs; sincos(6.2831853 * u.x, cs.y, cs.x);
		c += tex2Dlod(ReShade::BackBuffer, float4(uv + cs * sqrt(u.y) * TOPT_N_RADIUS * BUFFER_PIXEL_SIZE, 0.0, 0.0)).rgb;
	}}
	return float4(c * 0.125, 1.0);
}}
technique TOPT_N_{name}_1 < ui_tooltip = "Scatter pass, noise from {name}, 1 lookup + 4 taps"; >
{{ pass {{ VertexShader = PostProcessVS; PixelShader = TOPT_N_{name}_1PS; }} }}
technique TOPT_N_{name}_8 < ui_tooltip = "Scatter pass, noise from {name}, 8 lookups + 8 taps"; >
{{ pass {{ VertexShader = PostProcessVS; PixelShader = TOPT_N_{name}_8PS; }} }}
""")
    return "\n".join(out)


def _pairs(sigma: float, r: int) -> list:
    """1D Gaussian over -r..r as centre + linear pairs: [(offset, weight)]."""
    g = [math.exp(-0.5 * (i / sigma) ** 2) for i in range(r + 1)]
    taps = [(0.0, g[0])]
    for i in range(1, r + 1, 2):
        a, b = g[i], g[i + 1] if i + 1 <= r else 0.0
        taps += [(i + b / (a + b), a + b), (-(i + b / (a + b)), a + b)]
    s = sum(w for _, w in taps)
    return [(o, w / s) for o, w in taps]


def layout_effect() -> str:
    out = [HEAD, "#define TOPT_L_FMT RGBA8\n",
           "texture TOPT_L_tA { Width = BUFFER_WIDTH; Height = BUFFER_HEIGHT; Format = TOPT_L_FMT; };\n"
           "sampler TOPT_L_sA { Texture = TOPT_L_tA; AddressU = MIRROR; AddressV = MIRROR; };\n"
           "texture TOPT_L_tB { Width = BUFFER_WIDTH; Height = BUFFER_HEIGHT; Format = TOPT_L_FMT; };\n"
           "texture TOPT_L_tT { Width = BUFFER_HEIGHT; Height = BUFFER_WIDTH; Format = TOPT_L_FMT; }; // transposed\n"
           "sampler TOPT_L_sT { Texture = TOPT_L_tT; AddressU = MIRROR; AddressV = MIRROR; };\n"
           "sampler TOPT_L_sB { Texture = TOPT_L_tB; };\n"
           "sampler TOPT_L_sBB { Texture = ReShade::BackBufferTex; AddressU = MIRROR; AddressV = MIRROR; };\n"]
    for k in ("E0", "O0", "E1", "O1"):  # half-width targets: even / odd columns
        out.append(f"texture TOPT_L_t{k} {{ Width = BUFFER_WIDTH / 2; Height = BUFFER_HEIGHT; Format = TOPT_L_FMT; }};\n"
                   f"sampler TOPT_L_s{k} {{ Texture = TOPT_L_t{k}; AddressU = MIRROR; AddressV = MIRROR; "
                   f"MagFilter = POINT; MinFilter = POINT; }};\n")
    for sigma, r in ((6, 16), (12, 32)):
        t = _pairs(sigma, r)
        n = len(t)
        arr = ", ".join(f"float2({_f(o)}, {_f(w)})" for o, w in t)
        s = f"s{sigma}"
        out.append(f"""static const float2 TOPT_L_K{s}[{n}] = {{ {arr} }};
float3 TOPT_L_Blur{s}(sampler src, float2 uv, float2 d)
{{
	float3 c = 0.0;
	[unroll] for (int i = 0; i < {n}; i++)
		c += TOPT_L_K{s}[i].y * tex2Dlod(src, float4(uv + TOPT_L_K{s}[i].x * d, 0.0, 0.0)).rgb;
	return c;
}}
float4 TOPT_L_H_{s}PS(float4 p : SV_Position, float2 uv : TEXCOORD) : SV_Target {{ return float4(TOPT_L_Blur{s}(TOPT_L_sBB, uv, float2(BUFFER_RCP_WIDTH, 0.0)), 1.0); }}
float4 TOPT_L_V_{s}PS(float4 p : SV_Position, float2 uv : TEXCOORD) : SV_Target {{ return float4(TOPT_L_Blur{s}(TOPT_L_sA, uv, float2(0.0, BUFFER_RCP_HEIGHT)), 1.0); }}
float4 TOPT_L_V1_{s}PS(float4 p : SV_Position, float2 uv : TEXCOORD) : SV_Target {{ return float4(TOPT_L_Blur{s}(TOPT_L_sBB, uv, float2(0.0, BUFFER_RCP_HEIGHT)), 1.0); }}
float4 TOPT_L_H2_{s}PS(float4 p : SV_Position, float2 uv : TEXCOORD) : SV_Target {{ return float4(TOPT_L_Blur{s}(TOPT_L_sA, uv, float2(BUFFER_RCP_WIDTH, 0.0)), 1.0); }}
// transposed: texel (u, v) of T holds the H-blurred image at (v, u)
float4 TOPT_L_HT_{s}PS(float4 p : SV_Position, float2 uv : TEXCOORD) : SV_Target {{ return float4(TOPT_L_Blur{s}(TOPT_L_sBB, uv.yx, float2(BUFFER_RCP_WIDTH, 0.0)), 1.0); }}
float4 TOPT_L_VT_{s}PS(float4 p : SV_Position, float2 uv : TEXCOORD) : SV_Target {{ return float4(TOPT_L_Blur{s}(TOPT_L_sT, uv.yx, float2(BUFFER_RCP_HEIGHT, 0.0)), 1.0); }}
// split: one pixel per column pair, even / odd columns to two render targets
void TOPT_L_HS_{s}PS(float4 p : SV_Position, float2 uv : TEXCOORD, out float4 e : SV_Target0, out float4 o : SV_Target1)
{{
	const float2 c = float2((floor(p.x) * 2.0 + 0.5) * BUFFER_RCP_WIDTH, uv.y);
	e = float4(TOPT_L_Blur{s}(TOPT_L_sBB, c, float2(BUFFER_RCP_WIDTH, 0.0)), 1.0);
	o = float4(TOPT_L_Blur{s}(TOPT_L_sBB, c + float2(BUFFER_RCP_WIDTH, 0.0), float2(BUFFER_RCP_WIDTH, 0.0)), 1.0);
}}
void TOPT_L_VS_{s}PS(float4 p : SV_Position, float2 uv : TEXCOORD, out float4 e : SV_Target0, out float4 o : SV_Target1)
{{
	e = float4(TOPT_L_Blur{s}(TOPT_L_sE0, uv, float2(0.0, BUFFER_RCP_HEIGHT)), 1.0);
	o = float4(TOPT_L_Blur{s}(TOPT_L_sO0, uv, float2(0.0, BUFFER_RCP_HEIGHT)), 1.0);
}}
float4 TOPT_L_Merge_{s}PS(float4 p : SV_Position, float2 uv : TEXCOORD) : SV_Target
{{
	const float2 c = float2((floor(p.x * 0.5) + 0.5) / (BUFFER_WIDTH / 2), uv.y);
	const float3 e = tex2Dlod(TOPT_L_sE1, float4(c, 0.0, 0.0)).rgb;
	const float3 o = tex2Dlod(TOPT_L_sO1, float4(c, 0.0, 0.0)).rgb;
	return float4(frac(p.x * 0.5) > 0.25 ? o : e, 1.0);
}}
float4 TOPT_L_Copy_{s}PS(float4 p : SV_Position, float2 uv : TEXCOORD) : SV_Target {{ return tex2Dlod(TOPT_L_sB, float4(uv, 0.0, 0.0)); }}
technique TOPT_L_HV_{s} < ui_tooltip = "Separable sigma {sigma}: H pass, then V pass to the screen"; >
{{ pass {{ VertexShader = PostProcessVS; PixelShader = TOPT_L_H_{s}PS; RenderTarget = TOPT_L_tA; }}
   pass {{ VertexShader = PostProcessVS; PixelShader = TOPT_L_V_{s}PS; }} }}
technique TOPT_L_VH_{s} < ui_tooltip = "Separable sigma {sigma}: V pass, then H pass to the screen"; >
{{ pass {{ VertexShader = PostProcessVS; PixelShader = TOPT_L_V1_{s}PS; RenderTarget = TOPT_L_tA; }}
   pass {{ VertexShader = PostProcessVS; PixelShader = TOPT_L_H2_{s}PS; }} }}
technique TOPT_L_T_{s} < ui_tooltip = "Separable sigma {sigma}: H pass written transposed, V pass reads it along its rows"; >
{{ pass {{ VertexShader = PostProcessVS; PixelShader = TOPT_L_HT_{s}PS; RenderTarget = TOPT_L_tT; }}
   pass {{ VertexShader = PostProcessVS; PixelShader = TOPT_L_VT_{s}PS; }} }}
technique TOPT_L_HV3_{s} < ui_tooltip = "Separable sigma {sigma}: H, V into a texture, copy to the screen (3 passes, compare with Split)"; >
{{ pass {{ VertexShader = PostProcessVS; PixelShader = TOPT_L_H_{s}PS; RenderTarget = TOPT_L_tA; }}
   pass {{ VertexShader = PostProcessVS; PixelShader = TOPT_L_V_{s}PS; RenderTarget = TOPT_L_tB; }}
   pass {{ VertexShader = PostProcessVS; PixelShader = TOPT_L_Copy_{s}PS; }} }}
technique TOPT_L_Split_{s} < ui_tooltip = "Separable sigma {sigma}: H and V at half width writing even / odd columns to two targets, merged in the last pass"; >
{{ pass {{ VertexShader = PostProcessVS; PixelShader = TOPT_L_HS_{s}PS; RenderTarget0 = TOPT_L_tE0; RenderTarget1 = TOPT_L_tO0; }}
   pass {{ VertexShader = PostProcessVS; PixelShader = TOPT_L_VS_{s}PS; RenderTarget0 = TOPT_L_tE1; RenderTarget1 = TOPT_L_tO1; }}
   pass {{ VertexShader = PostProcessVS; PixelShader = TOPT_L_Merge_{s}PS; }} }}
""")
    return "\n".join(out)


def quad_effect(rows: dict, small_taps) -> str:
    """TOPT_Bench_Quad.fx: quad-shared single-pass blurs (scripts.quad_share) against the
    single-pass pinwheel of TOPT_Blur size 1 at the same sigma."""
    out = [HEAD]
    for t in (0.8, 1.0, 1.2):
        ok = [r for k, r in rows.items() if abs(float(k.split("_")[0]) - t) < 1e-6 and "medium" in r["ok"]]
        if not ok:
            continue
        r = min(ok, key=lambda r: r["reads"])
        n = r["reads"]
        s, w = r["positions"], r["weights"]
        tag = f"s{int(round(t * 10)):02d}"
        pos = ", ".join(f"float2({_f(x)}, {_f(y)})" for x, y in s)
        wts = ",\n\t".join("float4(" + ", ".join(_f(w[(a * 2 + b) * n + k]) for a, b in ((0, 0), (1, 0), (0, 1), (1, 1))) + ")"
                           for k in range(n))
        pin = small_taps(t)
        ptaps = ",\n\t".join(f"float3({_f(x)}, {_f(y)}, {_f(wt)})" for x, y, wt in pin)
        out.append(f"""// sigma {t}: {n} reads shared over the 2 x 2 quad ({4 * n} samples) vs a {len(pin)}-read pinwheel
static const float2 TOPT_Q_P{tag}[{n}] = {{ {pos} }};
// weight of read k for the pixel itself, its x, y and diagonal neighbour (by symmetry the same in every quad position)
static const float4 TOPT_Q_W{tag}[{n}] = {{
	{wts}
}};
float4 TOPT_Q_{tag}PS(float4 pos : SV_Position, float2 uv : TEXCOORD) : SV_Target
{{
	const float2 sgn = 1.0 - 4.0 * frac(floor(pos.xy) * 0.5); // +1 on even, -1 on odd pixels
	float3 c0 = 0.0, cx = 0.0, cy = 0.0, cd = 0.0;
	[unroll] for (int k = 0; k < {n}; k++)
	{{
		const float3 v = tex2Dlod(ReShade::BackBuffer, float4(uv + sgn * TOPT_Q_P{tag}[k] * BUFFER_PIXEL_SIZE, 0.0, 0.0)).rgb;
		c0 += TOPT_Q_W{tag}[k].x * v;
		cx += TOPT_Q_W{tag}[k].y * v;
		cy += TOPT_Q_W{tag}[k].z * v;
		cd += TOPT_Q_W{tag}[k].w * v;
	}}
	// the neighbours' values: X + sgn * ddx_fine(X), X + sgn * ddy_fine(X)
	const float3 nx = cx + sgn.x * ddx_fine(cx);
	const float3 ny = cy + sgn.y * ddy_fine(cy);
	const float3 dx = cd + sgn.x * ddx_fine(cd);
	const float3 nd = dx + sgn.y * ddy_fine(dx);
	return float4(c0 + nx + ny + nd, 1.0);
}}
static const float3 TOPT_Q_K{tag}[{len(pin)}] = {{
	{ptaps}
}};
float4 TOPT_Q_Pin{tag}PS(float4 pos : SV_Position, float2 uv : TEXCOORD) : SV_Target
{{
	float3 c = 0.0;
	[unroll] for (int i = 0; i < {len(pin)}; i++)
		c += TOPT_Q_K{tag}[i].z * tex2Dlod(ReShade::BackBuffer, float4(uv + TOPT_Q_K{tag}[i].xy * BUFFER_PIXEL_SIZE, 0.0, 0.0)).rgb;
	return float4(c, 1.0);
}}
technique TOPT_Q_Quad_{tag} < ui_tooltip = "sigma {t}: {n} reads shared over the 2x2 quad with ddx_fine / ddy_fine"; >
{{ pass {{ VertexShader = PostProcessVS; PixelShader = TOPT_Q_{tag}PS; }} }}
technique TOPT_Q_Pinwheel_{tag} < ui_tooltip = "sigma {t}: {len(pin)}-read exact pinwheel (TOPT_Blur size 1)"; >
{{ pass {{ VertexShader = PostProcessVS; PixelShader = TOPT_Q_Pin{tag}PS; }} }}
""")
    return "\n".join(out)
