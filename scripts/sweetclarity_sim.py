"""Clarity (local contrast) on the topt blur: halos of plain unsharp masking vs a guided-filter base layer.

    python -m scripts.sweetclarity_sim

Brightness Y in 0..1 (the screen's stored values). Detail = Y - base, output Y + s * detail.
* unsharp: base = G(Y), a Gaussian of sigma.
* guided (He et al.'s guided filter with the picture as its own guide, Gaussian windows): from m = G(Y) and
  c = G(Y^2): var = c - m^2, a = var / (var + eps), b = m (1 - a); base = G(a) Y + G(b) (the full filter),
  or a Y + b without the second averaging ("fast"). Where the local spread is far above sqrt(eps) (a strong
  edge) a ~ 1 and the base follows the picture: no detail there, no halo; flat-ish texture (spread below
  sqrt(eps)) gets the full boost.
Test picture (1D across 1024 px, 2D-equivalent Gaussians): a step 0.2 -> 0.7 at x = 512, plus a texture
(sinusoid of amplitude A levels, period 8 px) on the left half only from 64 px away from the step.
Metrics: texture gain (output / input amplitude far from the step), halo = the largest overshoot past the
step's two levels in the textureless right half (8-bit levels), and the texture gain near the step.
Writes results/sweetclarity_sim.md.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
from scipy.ndimage import gaussian_filter1d

ROOT = Path(__file__).resolve().parent.parent
N = 1024


def picture(A: float):
    x = np.arange(N)
    y = np.where(x < 512, 0.2, 0.7)
    tex = (x < 512 - 64) * (A / 255) * np.sin(2 * np.pi * x / 8)
    return y + tex, tex


def G(v, s):
    return gaussian_filter1d(v, s, mode="reflect")


def unsharp(y, s, sig, eps):
    return y + s * (y - G(y, sig))


def guided(y, s, sig, eps, full=True):
    m, c = G(y, sig), G(y * y, sig)
    a = np.maximum(c - m * m, 0) / (np.maximum(c - m * m, 0) + eps)
    b = m * (1 - a)
    base = (G(a, sig) * y + G(b, sig)) if full else (a * y + b)
    return y + s * (y - base)


def metrics(f, s, sig, eps, A):
    y, tex = picture(A)
    o = f(y, s, sig, eps)
    far = slice(64, 512 - 128)
    gain = np.std(o[far] - np.mean(o[far])) / np.std(tex[far])
    near = slice(512 - 64 - 16, 512 - 64)
    gnear = np.std(o[near] - (y - tex)[near]) / np.std(tex[near]) if np.std(tex[near]) > 0 else 0
    right = o[512:]
    halo = max(np.max(right) - 0.7, 0.2 - np.min(o[400:512] - tex[400:512]), 0.7 - np.min(right[0:1]) * 0) * 255
    over = max(np.max(o[512:]) - 0.7, 0) * 255          # bright rim on the bright side
    under = max(0.2 - np.min((o - tex)[512 - 64:512]), 0) * 255   # dark rim on the dark side
    return gain, max(over, under)


def main():
    sig = 16.0
    lines = ["# Clarity: halos of unsharp masking vs a guided-filter base", "",
             "Generated by `python -m scripts.sweetclarity_sim` (see its docstring). Sigma 16 px; step 0.2 -> 0.7",
             "(127 levels); texture amplitude A levels, period 8 px. Strength s is set per method so the far",
             "texture gain is 1.5 (or the most the method reaches at s = 4); halo = largest overshoot past the step",
             "(8-bit levels).", "",
             "| method | eps (levels) | A | s | texture gain | halo (levels) |", "|---|---:|---:|---:|---:|---:|"]
    for A in (2, 6, 12):
        for name, f, eps_l in [("unsharp", unsharp, 0)] + [(n, f, e) for e in (6, 12, 24)
                                                           for n, f in (("guided", guided),
                                                                        ("guided fast", lambda y, s, g, e: guided(y, s, g, e, False)))]:
            eps = (eps_l / 255) ** 2
            lo, hi = 0.0, 4.0
            for _ in range(40):
                s = (lo + hi) / 2
                g, _ = metrics(f, s, sig, eps, A)
                lo, hi = (s, hi) if g < 1.5 else (lo, s)
            g, h = metrics(f, s, sig, eps, A)
            lines.append(f"| {name} | {eps_l if eps_l else '-'} | {A} | {s:.2f} | {g:.2f} | {h:.1f} |")
    (ROOT / "results" / "sweetclarity_sim.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
